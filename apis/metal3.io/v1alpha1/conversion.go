// v1alpha1 is the storage version. v1beta1 is the conversion hub.
//
// The mechanical field-by-field conversion is generated by conversion-gen into
// zz_generated.conversion.go (regenerate with `make generate`). Fields that
// conversion-gen cannot handle are converted by the manual Convert_* functions
// in this file.
//
// Following the pattern used by cluster-api-provider-metal3, cluster-api and
// cluster-api-provider-openstack, ConvertTo/ConvertFrom additionally use the
// conversion-data annotation (MarshalData/UnmarshalData, defined locally in
// conversion_data.go) to make the round-trip lossless.
//
// Unlike cluster-api, where the hub is also the storage version, here the
// spoke (v1alpha1) is stored. The annotation therefore stores SPOKE-only
// fields (fields that exist in v1alpha1 but were removed from v1beta1) on the
// HUB, so that they survive a spoke -> hub -> spoke round-trip, e.g. when a
// v1beta1 client reads and updates an object that is stored as v1alpha1:
//
//   - ConvertTo (spoke -> hub) calls MarshalData to stash the spoke-only fields
//     in an annotation on the hub. Only the removed fields are stashed, not the
//     whole object, and only when at least one of them is set, to keep the
//     annotation small.
//   - ConvertFrom (hub -> spoke) calls UnmarshalData to restore any previously
//     stashed spoke-only fields onto the freshly converted spoke object. The
//     annotation is removed from the spoke so it never reaches storage.
//
// Spoke-only fields:
//   - Spec.Firmware and Status.Provisioning.Firmware were removed in v1beta1
//     since no maintained driver supports them any more.

// --- BareMetalHost ---

// ConvertTo converts this BareMetalHost (v1alpha1) to the Hub version (v1beta1).
func (src *BareMetalHost) ConvertTo(dstRaw conversion.Hub) error {
	dst := dstRaw.(*metal3apiv1beta1.BareMetalHost)
	if err := Convert_v1alpha1_BareMetalHost_To_v1beta1_BareMetalHost(src, dst, nil); err != nil {
		return err
	}
	return stashBareMetalHostSpokeOnlyFields(src, dst)
}

// ConvertFrom converts the Hub version (v1beta1) to this BareMetalHost (v1alpha1).
func (dst *BareMetalHost) ConvertFrom(srcRaw conversion.Hub) error {
	src := srcRaw.(*metal3apiv1beta1.BareMetalHost)
	if err := Convert_v1beta1_BareMetalHost_To_v1alpha1_BareMetalHost(src, dst, nil); err != nil {
		return err
	}
	return restoreBareMetalHostSpokeOnlyFields(dst)
}

// Convert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec converts the
// spec, dropping Firmware which does not exist in v1beta1. ConvertTo preserves
// it in the conversion-data annotation.
func Convert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec(in *BareMetalHostSpec, out *metal3apiv1beta1.BareMetalHostSpec, s apimachineryconversion.Scope) error {
	return autoConvert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec(in, out, s)
}

// Convert_v1alpha1_ProvisionStatus_To_v1beta1_ProvisionStatus converts the
// provisioning status, dropping Firmware which does not exist in v1beta1.
// ConvertTo preserves it in the conversion-data annotation.
func Convert_v1alpha1_ProvisionStatus_To_v1beta1_ProvisionStatus(in *ProvisionStatus, out *metal3apiv1beta1.ProvisionStatus, s apimachineryconversion.Scope) error {
	return autoConvert_v1alpha1_ProvisionStatus_To_v1beta1_ProvisionStatus(in, out, s)
}

// stashBareMetalHostSpokeOnlyFields stores the v1alpha1-only fields of src in
// the conversion-data annotation on dst. Only those fields are copied into the
// stashed object, and nothing is stashed when none of them is set.
func stashBareMetalHostSpokeOnlyFields(src *BareMetalHost, dst *metal3apiv1beta1.BareMetalHost) error {
	stash := &BareMetalHost{}
	stash.Spec.Firmware = src.Spec.Firmware
	stash.Status.Provisioning.Firmware = src.Status.Provisioning.Firmware

	if stash.Spec.Firmware == nil && stash.Status.Provisioning.Firmware == nil {
		return nil
	}

	// The generated conversion shares the annotations map between src and
	// dst; clone it so the annotation is only added to the hub.
	dst.SetAnnotations(maps.Clone(dst.GetAnnotations()))
	return MarshalData(stash, dst)
}

// restoreBareMetalHostSpokeOnlyFields restores the v1alpha1-only fields
// stashed by stashBareMetalHostSpokeOnlyFields, and removes the
// conversion-data annotation from dst.
func restoreBareMetalHostSpokeOnlyFields(dst *BareMetalHost) error {
	if _, ok := dst.GetAnnotations()[DataAnnotation]; !ok {
		return nil
	}

	// The generated conversion shares the annotations map between the hub
	// and dst; clone it so removing the annotation does not modify the hub.
	dst.SetAnnotations(maps.Clone(dst.GetAnnotations()))
	stash := &BareMetalHost{}
	if _, err := UnmarshalData(dst, stash); err != nil {
		return err
	}
	if len(dst.GetAnnotations()) == 0 {
		dst.SetAnnotations(nil)
	}

	dst.Spec.Firmware = stash.Spec.Firmware
	dst.Status.Provisioning.Firmware = stash.Status.Provisioning.Firmware
	return nil
}

